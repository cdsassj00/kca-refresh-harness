/* ── 그리기 ─────────────────────────────────────────────────── */

function legendHtml(leg) {
  const rows = leg.rows.map(([label, tone, short, desc]) =>
    `<tr><td><span class="pill p-${tone}">${label}</span></td>` +
    `<td class="lg-short">${short}</td><td class="lg-desc">${desc || ''}</td></tr>`).join('');
  return `<div class="lg">
    <h4>${leg.title}</h4>
    ${leg.note ? `<p class="muted lg-note">${leg.note}</p>` : ''}
    <table class="tbl lg-tbl"><tbody>${rows}</tbody></table>
  </div>`;
}

function helpHtml(h) {
  const how = h.how.map(s => `<li>${s}</li>`).join('');
  const legs = (h.legends || []).map(legendHtml).join('');
  return `<details class="helpbox">
    <summary><span class="help-ico" aria-hidden="true">?</span> 이 화면을 어떻게 읽나</summary>
    <div class="help-body">
      <p class="help-lead">${h.lead}</p>
      <p class="help-what"><b>무엇을 보는 곳인가</b> — ${h.what}</p>
      <ol class="help-how">${how}</ol>
      ${legs ? `<div class="lg-wrap">${legs}</div>` : ''}
    </div>
  </details>`;
}

/* 화면마다 맨 위에 한 번만 끼워 넣는다. 접힘 여부는 이 브라우저에만 기억한다. */
function mountHelp() {
  Object.entries(HELP).forEach(([view, h]) => {
    const sec = document.getElementById('view-' + view);
    if (!sec || sec.querySelector('.helpbox')) return;
    const box = document.createElement('div');
    box.innerHTML = helpHtml(h);
    const el = box.firstElementChild;
    let open = true;
    try { open = localStorage.getItem('help:' + view) !== 'closed'; } catch (e) { /* 사생활 보호 모드 */ }
    el.open = open;
    el.addEventListener('toggle', () => {
      try { localStorage.setItem('help:' + view, el.open ? 'open' : 'closed'); } catch (e) { /* 무시 */ }
    });
    sec.insertBefore(el, sec.firstChild);
  });
}

/* app.js 보다 먼저 읽히므로, 화면이 다 그려진 뒤에 끼워 넣는다. */
if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', mountHelp);
} else {
  mountHelp();
}

window.KCA_HELP = { mountHelp, HELP, LEG_GRADE, LEG_VERDICT, LEG_STATUS, LEG_ACTION, LEG_KIND };
